"""Write results.md into a training run folder: setup, training curve, scores, eval_sizes results and plots in one page.

Reads what train.py and eval_sizes.py leave in the run folder (args.yaml, results.csv, scores.md, eval/*.json and
ultralytics' plots). train.py and eval_sizes.py call it when they finish; run it by hand after changing a run.

Usage:
    python src/detection/report.py runs/rgb/yolo26n_e100 [runs/thermal/...]
    python src/detection/report.py --all
"""

import argparse
import json
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[2]
PLOTS = [  # (file, caption)
    ("results.png", "Losses and val metrics per epoch"),
    ("BoxPR_curve.png", "Precision against recall on the combined val set"),
    ("BoxF1_curve.png", "F1 against confidence threshold"),
    ("BoxP_curve.png", "Precision against confidence threshold"),
    ("BoxR_curve.png", "Recall against confidence threshold"),
    ("confusion_matrix_normalized.png", "Confusion matrix (person against background), normalised"),
    ("labels.jpg", "Training labels: box positions and sizes"),
    ("val_batch0_labels.jpg", "Val batch 0, labels"),
    ("val_batch0_pred.jpg", "Val batch 0, predictions"),
]
NOTES = {  # eval file stem -> what the split is, where the name alone doesn't say
    "heridal-test": "HERIDAL's held-out locations (MED, BRA, CAP, SB, BLI, CAB), whole 853×640 frames.",
    "heridal-test-last": "As heridal-test, with last.pt (the final epoch) instead of best.pt.",
    "heridal-v1-unique": "First HERIDAL conversion, before the location split: one frame per distinct view over all 1,579 frames.",
    "heridal-v1-roboflow-test": "First HERIDAL conversion, before the location split: Roboflow's 101-image test split.",
}


def table(df):
    return df.to_markdown(index=False)


def training(run):
    df = pd.read_csv(run / "results.csv")
    df.columns = df.columns.str.strip()
    ap50, ap = df["metrics/mAP50(B)"], df["metrics/mAP50-95(B)"]
    best = (0.1 * ap50 + 0.9 * ap).idxmax()  # ultralytics' fitness, which picks best.pt
    peak = ap50.idxmax()
    rows = [
        ("Epochs run", len(df)),
        ("best.pt from epoch", f"{int(df.epoch[best])} (val AP50 {ap50[best]:.3f}, AP50-95 {ap[best]:.3f})"),
        ("Highest val AP50", f"{ap50[peak]:.3f} at epoch {int(df.epoch[peak])}"),
        ("Last epoch", f"AP50 {ap50.iloc[-1]:.3f}, AP50-95 {ap.iloc[-1]:.3f}"),
        ("Training time", f"{df.time.iloc[-1] / 60:.0f} min"),  # ultralytics logs cumulative seconds
    ]
    every = max(1, len(df) // 10)
    curve = df.iloc[list(range(every - 1, len(df), every)) + ([best] if (best + 1) % every else [])].sort_index()
    curve = pd.DataFrame({"epoch": curve.epoch, "AP50": curve["metrics/mAP50(B)"], "AP50-95": curve["metrics/mAP50-95(B)"],
                          "P": curve["metrics/precision(B)"], "R": curve["metrics/recall(B)"]}).round(3)
    return "\n".join(f"- {k}: {v}" for k, v in rows), table(curve)


def eval_sizes(run):
    out = []
    for f in sorted((run / "eval").glob("*.json")):
        rows = []
        for r in json.loads(f.read_text()):
            row = {"imgsz": r["imgsz"], "tiled": "640" if r["tile"] else "no", "IoU": r["iou"], "images": r["images"],
                   "persons": r["persons"], "AP50": r["ap"], "P@0.25": r["precision"], "R@0.25": r["recall"]}
            row.update({f"R {k} px": f"{v['recall']:.2f} ({v['n']})" for k, v in r["recall_by_size"].items()})
            rows.append(row)
        note = f"{NOTES[f.stem]}\n\n" if f.stem in NOTES else ""
        out.append(f"#### {f.stem}\n\n{note}" + table(pd.DataFrame(rows).fillna("")))
    return "\n\n".join(out)


def data_lists(yaml):
    """Dataset names in a run's data.yaml: {train name: times listed}, [val names]."""
    out, key = {"train": {}, "val": {}}, None
    for line in yaml.read_text().splitlines():
        if line.endswith(":"):
            key = line[:-1]
        elif line.startswith("  - ") and key in out:
            name = Path(line[4:]).parents[1].name  # .../<name>/images/<split>
            out[key][name] = out[key].get(name, 0) + 1
    return out["train"], list(out["val"])


def write(run):
    run = Path(run).resolve()
    args = dict(line.split(": ", 1) for line in (run / "args.yaml").read_text().splitlines() if ": " in line)
    mod = run.parent.name
    parts = [f"# {mod} / {run.name}", "",
             "Generated by `src/detection/report.py` from the files in this folder. Metric definitions: "
             "[research/datasets/README.md](../../../research/datasets/README.md#reading-the-metrics).", "",
             "## Setup", "",
             f"- Model: `{args['model']}`, imgsz {args['imgsz']}, batch {args['batch']}, {args['epochs']} epochs, seed {args['seed']}, "
             f"random rescale ±{args['scale']}"]
    scores = run / "scores.md"
    if (run / "data.yaml").exists():
        train, val = data_lists(run / "data.yaml")
        parts.append(f"- Train: {', '.join(f'{n} ×{k}' if k > 1 else n for n, k in train.items())}")
        parts.append(f"- Val (picks best.pt): {', '.join(val)}")
    elif scores.exists():  # runs before data.yaml: every dataset of the modality, train and val
        lines = scores.read_text().splitlines()
        names = [l.split("|")[1].strip() for l in lines[4:] if l.startswith("|")]
        parts.append(f"- Data: {', '.join(n for n in dict.fromkeys(names) if n != 'all')}")
    if (run / "results.csv").exists():
        summary, curve = training(run)
        parts += ["", "## Training", "", summary, "", "Val metrics (combined val set) every few epochs:", "", curve]
    if scores.exists():
        parts += ["", "## Scores (ultralytics, best.pt)", "",
                  "P and R at the confidence with the best F1. `all` is every val set together.", "",
                  "\n".join(scores.read_text().splitlines()[2:])]
    if (run / "eval").is_dir() and any((run / "eval").glob("*.json")):
        parts += ["", "## eval_sizes.py", "",
                  "AP50 by `eval_sizes.py`; P and R at confidence 0.25; recall by person size (√area in px at the model "
                  "input, or native px when tiled), with the number of persons in brackets.", "", eval_sizes(run)]
    plots = [(f, c) for f, c in PLOTS if (run / f).exists()]
    if plots:
        parts += ["", "## Plots", ""] + [f"{c}:\n\n![{c}]({f})\n" for f, c in plots]
    (run / "results.md").write_text("\n".join(parts).rstrip() + "\n")
    print(f"wrote {run / 'results.md'}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("runs", nargs="*", type=Path)
    ap.add_argument("--all", action="store_true", help="every run under runs/<modality>/")
    args = ap.parse_args()
    runs = args.runs + (sorted(p.parent for p in (REPO / "runs").glob("*/*/args.yaml")) if args.all else [])
    assert runs, "give run folders or --all"
    for r in runs:
        write(r)


if __name__ == "__main__":
    main()
